// Compile reviewed words into the package: dictionary/data/reviewed.jsonl ->
// src/generated/reviewed.ts. Only accepted and corrected entries ship;
// "unsure" ones wait for a second look.
//
//   npm run dictionary
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const input = join(root, 'dictionary', 'data', 'reviewed.jsonl');
const output = join(root, 'src', 'generated', 'reviewed.ts');

const latest = new Map();
for (const line of readFileSync(input, 'utf8').split('\n')) {
  if (!line.trim()) continue;
  const entry = JSON.parse(line);
  // Same rule as the review server: a skip never erases a decision.
  if (entry.status === 'skipped' && latest.has(entry.word) && latest.get(entry.word).status !== 'skipped') continue;
  latest.set(entry.word, entry);
}

const words = [...latest.values()]
  .filter((e) => (e.status === 'accepted' || e.status === 'corrected') && e.script)
  .sort((a, b) => a.word.localeCompare(b.word, 'mn'));

const escape = (s) => JSON.stringify(s).replace(/[\u0080-￿]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, '0')}`);

mkdirSync(dirname(output), { recursive: true });
writeFileSync(
  output,
  `// Generated by dictionary/tools/build-dictionary.mjs from dictionary/data/reviewed.jsonl.
// Do not edit by hand: review words with \`npm run review\`, then \`npm run dictionary\`.
//
// Open Mongolian script dictionary, CC BY-SA 4.0 (dictionary/LICENSE, dictionary/NOTICE).
// Human-reviewed Cyrillic word forms and their traditional script spelling.
// Escaped so invisible controls (NNBSP, MVS, FVS) survive any editor.

import type { MongolDictionary } from '../convert.js';

export const REVIEWED: MongolDictionary = {
${words.map((e) => `  ${JSON.stringify(e.word)}: ${escape(e.script)},`).join('\n')}
};
`,
);
console.log(`${words.length} reviewed words -> ${output}`);
